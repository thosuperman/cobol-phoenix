"""phoenix_runtime - COBOL data and arithmetic semantics for generated Python.

This module is vendored verbatim into every project generated by COBOL Phoenix.
It depends only on the Python standard library.

Semantics follow GnuCOBOL 3.2 (default dialect) for the supported subset:

* storage is byte based (one ``bytearray`` per 01/77 record), so REDEFINES,
  group moves and CALL BY REFERENCE behave like COBOL;
* numeric values are ``decimal.Decimal``; intermediate results use a 64 digit
  context that truncates (ROUND_DOWN); stores truncate unless ROUNDED
  (round half away from zero);
* high-order truncation on overflow unless ON SIZE ERROR is specified.
"""

from __future__ import annotations

import datetime as _dt
