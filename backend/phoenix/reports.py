"""Markdown exports: business rules, migration report, verification report."""

from __future__ import annotations

import datetime as dt

from .config import VERSION


def _now() -> str:
    return dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")


def rules_markdown(project: dict, rules: list[dict]) -> str:
    out = [f"# Business rules — {project['name']}", "", f"Generated by COBOL Phoenix {VERSION} on {_now()}.", ""]
    out += [
        "Every rule below was extracted deterministically from the parsed COBOL source. Line ranges refer to the original files.",
        "Verification status semantics: **VERIFIED** = executed by at least one differential case where GnuCOBOL and Python agreed and by no failing case;",
        "**FAILED** = executed by a failing case; **NOT_EXERCISED** = not executed by any case; **NOT_RUN** = no verification run yet; **UNSUPPORTED** = contains unsupported constructs.",
        "",
    ]
    by_prog: dict[str, list[dict]] = {}
    for r in rules:
        by_prog.setdefault(r["program"], []).append(r)
    for prog, rs in by_prog.items():
        out += [f"## {prog}", ""]
        for r in rs:
            v = r.get("verification", {})
            out += [f"### {r['name']}", "", f"- **Source:** `{r['file']}` lines {r['line_start']}–{r['line_end']} (paragraph `{r['paragraph']}`)", f"- **Status:** {v.get('status', r['status'])} (statement coverage {v.get('coverage_pct', 0)}%)", f"- **Description:** {r['description']} _({r['description_source']})_"]
            if r["inputs"]:
                out.append(f"- **Inputs:** {', '.join(r['inputs'])}")
            if r["outputs"]:
                out.append(f"- **Outputs:** {', '.join(r['outputs'])}")
            for c in r["conditions"]:
                out.append(f"- Condition (line {c['line']}): `{c['text']}`")
            for c in r["calculations"]:
                out.append(f"- Calculation (line {c['line']}): `{c['text']}`")
            for t in r["decision_tables"]:
                out += ["", f"Decision table on `{t['subject']}` (line {t['line']}):", "", "| WHEN | Actions |", "|---|---|"]
                for row in t["rows"]:
                    out.append(f"| `{row['when']}` | {'; '.join(row['actions']) or '—'} |")
            out.append("")
    return "\n".join(out)


def verification_markdown(project: dict, report: dict, mutation: dict | None) -> str:
    s = report["summary"]
    ex = report["executor"]
    out = [
        f"# Differential verification report — {report['entry']}",
        "",
        f"Project: {project['name']} · Generated by COBOL Phoenix {VERSION} on {_now()}",
        "",
        f"> {report['claim']}",
        "",
        "## Environment",
        "",
        f"- COBOL executor: `{ex['name']}` ({'available' if ex['available'] else 'unavailable'}) {ex.get('cobc_version') or ''}",
        f"- Compile: {'OK' if report['compile']['ok'] else 'FAILED'} — `{report['compile']['command']}`",
        f"- Fixed date/time for both runtimes: {report['fixed_datetime']}",
        f"- Harness mode: {report['mode']}",
    ]
    if ex.get("error"):
        out.append(f"- Executor note: {ex['error']}")
    if report.get("mutation"):
        m = report["mutation"]
        out += ["", f"**This run verified a deliberately mutated build** (`{m['id']}`: {m['detail']})."]
    out += [
        "",
        "## Summary",
        "",
        "| Total | VERIFIED | FAILED | NOT_VERIFIABLE | UNSUPPORTED | Statement coverage |",
        "|---|---|---|---|---|---|",
        f"| {s['total']} | {s['verified']} | {s['failed']} | {s['not_verifiable']} | {s['unsupported']} | {s['statements_executed']}/{s['statements_total']} ({s['coverage_pct']}%) |",
        "",
        "| Case kind | Results |",
        "|---|---|",
    ]
    for kind, d in s["by_kind"].items():
        out.append(f"| {kind} | {', '.join(f'{k}: {v}' for k, v in d.items())} |")
    failed = [c for c in report["cases"] if c["status"] == "FAILED"]
    if failed:
        out += ["", "## Differences", ""]
        for c in failed[:50]:
            out += [f"### {c['id']} — {c['description']}", "", "| Parameter | Field | COBOL | Python | Δ | Source |", "|---|---|---|---|---|---|"]
            for d in c["diffs"][:20]:
                out.append(f"| {d.get('param', '')} | {d.get('field', '')} | `{str(d.get('cobol', '')).strip()[:60]}` | `{str(d.get('python', '')).strip()[:60]}` | {d.get('delta', '')} | {d.get('loc', '')} |")
            out.append("")
    other = [c for c in report["cases"] if c["status"] in ("NOT_VERIFIABLE", "UNSUPPORTED")]
    if other:
        out += ["", "## Not verified", ""]
        for c in other[:30]:
            out.append(f"- `{c['id']}` {c['status']}: {c['note']}")
    if mutation:
        out += [
            "",
            "## Mutation analysis (test-suite strength)",
            "",
            f"Reference outputs: {mutation.get('reference', 'gnucobol')}. {mutation['killed']} of {mutation['evaluated']} single-fault mutants were detected ({mutation['score_pct']}%).",
            "Survivors indicate behaviour the current cases do not exercise, or equivalent mutants (e.g. ROUNDED on an exact sum).",
            "",
            "| Mutant | Change | Result |",
            "|---|---|---|",
        ]
        for m in mutation["mutants"]:
            out.append(f"| `{m['id']}` | {m['detail']} | {m['status']} |")
    out += ["", "## Cases", "", "| Case | Kind | Status | Description |", "|---|---|---|---|"]
    for c in report["cases"]:
        out.append(f"| {c['id']} | {c['kind']} | {c['status']} | {c['description'][:90]} |")
    return "\n".join(out) + "\n"


def migration_markdown(project: dict, analysis: dict, rules: list[dict], generations: list[dict], latest: dict | None) -> str:
    o = analysis["overview"]
    out = [
        f"# Modernization report — {project['name']}",
        "",
        f"Generated by COBOL Phoenix {VERSION} on {_now()}. Source: {project['source_kind']} {project.get('source_ref') or ''}. License: {project.get('license') or 'not detected'}.",
        "",
        "## Inventory",
        "",
        "| Programs | Copybooks | Source lines | Dependencies | Business rules | Unsupported constructs | Complexity |",
        "|---|---|---|---|---|---|---|",
        f"| {o['programs']} | {o['copybooks']} | {o['source_lines']} | {o['dependencies']} | {o['business_rules']} | {o['unsupported_constructs']} | {o['complexity_band']} ({o['complexity_score']}) |",
        "",
        "Complexity score = statements×1 + decision points×3 + paragraphs×2 + CALLs×4 + unsupported×10 + data items×0.25 (per program; project band from the average).",
        "",
        "## Programs",
        "",
        "| Program | File | Kind | Statements | Decisions | Score | Band | Rules | Unsupported |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p in analysis["programs"]:
        m = p["metrics"]
        out.append(f"| {p['program_id']} | `{p['file']}` | {p['kind']} | {m['statements']} | {m['decision_points']} | {m['score']} | {m['band']} | {p['rules']} | {p['unsupported']} |")
    if analysis["unsupported"]:
        out += ["", "## Unsupported constructs", "", "| Program | Location | Construct | Category | Reason |", "|---|---|---|---|---|"]
        for u in analysis["unsupported"][:200]:
            out.append(f"| {u['program']} | {u['file']}:{u['line']} | {u['construct']} | {u['category']} | {u['reason']} |")
    out += ["", "## Generated services", ""]
    if generations:
        out += ["| Generation | Entry | Mode | Statements translated | Unsupported | Mutation |", "|---|---|---|---|---|---|"]
        for g in generations:
            sm = g["summary"]
            out.append(f"| {g['id']} | {g['entry']} | {sm.get('mode')} | {sm.get('statements')} | {len(sm.get('unsupported', []))} | {g.get('mutation_id') or '—'} |")
    else:
        out.append("No Python service generated yet.")
    out += ["", "## Verification", ""]
    if latest:
        s = latest["summary"]
        out += [f"Latest run ({latest['entry']}): {s['verified']}/{s['total']} VERIFIED, {s['failed']} FAILED, {s['not_verifiable']} NOT_VERIFIABLE, {s['unsupported']} UNSUPPORTED; statement coverage {s['coverage_pct']}%.", "", f"> {latest['claim']}"]
    else:
        out.append("No verification run yet.")
    status_counts: dict[str, int] = {}
    for r in rules:
        st = r.get("verification", {}).get("status", "NOT_RUN")
        status_counts[st] = status_counts.get(st, 0) + 1
    out += ["", "## Business rule status", "", "| Status | Rules |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(status_counts.items())]
    out += ["", "## Recommended next steps", "", "1. Add fixtures for rules marked NOT_EXERCISED and for surviving mutants.", "2. Replace or isolate unsupported constructs (file I/O, embedded SQL) behind adapters before migrating those programs.", "3. Keep the differential suite in CI while the COBOL system is still authoritative."]
    return "\n".join(out) + "\n"
